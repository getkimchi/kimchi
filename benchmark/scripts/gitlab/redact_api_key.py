#!/usr/bin/env python3
"""Walk benchmark/terminal-bench-2/jobs and redact injected API keys from all files.

Replaces the inline `.redact-api-key` anchor in the CI YAML with a tested script.
Uses pure Python file IO (not a subprocess shell pipeline) so it works the same
way regardless of which shell or subprocess semantics are active.

Why a custom script instead of a dedicated secret-scanning tool? This runs only
against artifacts generated by this benchmark, and it knows the exact secret
values it injected (see REDACTED_ENV_KEYS). The narrow scope means a plain
string replace is sufficient and we don't need to ship a scanner binary into
the chunk job. For richer needs, the standard alternatives are:

- Gitleaks: best fit for CI/file/directory scanning; supports --redact.
- TruffleHog: stronger high-confidence secret discovery and verification.
- detect-secrets: baseline-driven adoption in Python/pre-commit workflows.

If we ever need to scan generated artifacts for unknown secrets (not just the
one key we know about), switch to Gitleaks.
"""

from __future__ import annotations

import os
from pathlib import Path

REDACTED_MARKER = b"[redacted]"
# Env vars holding secrets this benchmark injects into agent environments.
# KIMCHI_API_KEY routes kimchi-dev/* models; OPENROUTER_API_KEY routes
# openrouter/* models; ANTHROPIC_API_KEY routes anthropic/* models
# (claude-code-standard).
REDACTED_ENV_KEYS = ("KIMCHI_API_KEY", "OPENROUTER_API_KEY", "ANTHROPIC_API_KEY")


def redact_tree(root: Path, secrets: list[bytes]) -> None:
    """Redact every occurrence of each secret in every file under ``root``.

    Reusable by the checkpoint pipeline: the GCS checkpoint plugin stages a
    trial into a temp directory, then calls this on the staging copy before
    archiving — so an unredacted secret can never reach GCS.

    Args:
        root: directory tree to walk recursively.
        secrets: byte strings to replace with :data:`REDACTED_MARKER`. Empty
            or whitespace-only entries are ignored. Non-file entries (dirs,
            symlinks) are skipped.
    """
    needles = [s for s in secrets if s and s.strip()]
    if not needles:
        return
    for path in root.rglob("*"):
        if not path.is_file() or path.is_symlink():
            continue
        data = path.read_bytes()
        if not any(needle in data for needle in needles):
            continue
        new_data = data
        for needle in needles:
            new_data = new_data.replace(needle, REDACTED_MARKER)
        path.write_bytes(new_data)


def main() -> int:
    secrets = [
        value.encode("utf-8")
        for value in (os.environ.get(name, "") for name in REDACTED_ENV_KEYS)
        if value
    ]
    if not secrets:
        return 0

    jobs_dir = Path(os.environ.get("BENCHMARK_RESULTS_DIR", "benchmark/terminal-bench-2/jobs"))
    if not jobs_dir.is_dir():
        return 0

    redact_tree(jobs_dir, secrets)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
