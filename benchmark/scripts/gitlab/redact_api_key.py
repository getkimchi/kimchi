#!/usr/bin/env python3
"""Walk benchmark/terminal-bench-2/jobs and redact KIMCHI_API_KEY from all files.

Replaces the inline `.redact-api-key` anchor in the CI YAML with a tested script.
Uses pure Python file IO (not a subprocess shell pipeline) so it works the same
way regardless of which shell or subprocess semantics are active.

Why a custom script instead of a dedicated secret-scanning tool? This runs only
against artifacts generated by this benchmark, and it knows the single secret
value it injected (KIMCHI_API_KEY). The narrow scope means a plain string
replace is sufficient and we don't need to ship a scanner binary into the
chunk job. For richer needs, the standard alternatives are:

- Gitleaks: best fit for CI/file/directory scanning; supports --redact.
- TruffleHog: stronger high-confidence secret discovery and verification.
- detect-secrets: baseline-driven adoption in Python/pre-commit workflows.

If we ever need to scan generated artifacts for unknown secrets (not just the
one key we know about), switch to Gitleaks.
"""

from __future__ import annotations

import os
from pathlib import Path


def main() -> int:
    api_key = os.environ.get("KIMCHI_API_KEY", "")
    if not api_key:
        return 0

    jobs_dir = Path(os.environ.get("BENCHMARK_RESULTS_DIR", "benchmark/terminal-bench-2/jobs"))
    if not jobs_dir.is_dir():
        return 0

    redacted_marker = b"[redacted]"
    needle = api_key.encode("utf-8")

    for path in jobs_dir.rglob("*"):
        if not path.is_file():
            continue
        try:
            data = path.read_bytes()
        except OSError:
            continue
        if needle not in data:
            continue
        new_data = data.replace(needle, redacted_marker)
        try:
            path.write_bytes(new_data)
        except OSError:
            continue

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
