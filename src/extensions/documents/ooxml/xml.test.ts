import { describe, expect, it } from "vitest"
import { fragmentNamespaces, parseFragment, parseXml, rootNamespaceDecls, serializeFragmentChildren } from "./xml.js"

const W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
const W14 = "http://schemas.microsoft.com/office/word/2010/wordml"

describe("rootNamespaceDecls", () => {
	it("extracts prefixed and default declarations", () => {
		const decls = rootNamespaceDecls(`<w:document xmlns:w="${W}" xmlns="urn:default"><w:body/></w:document>`)
		expect(decls).toEqual([`xmlns:w="${W}"`, `xmlns="urn:default"`])
	})

	it("skips the XML declaration and comments before the root", () => {
		const decls = rootNamespaceDecls(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<!-- generated by a tool -->
<w:document xmlns:w="${W}"/>`)
		expect(decls).toEqual([`xmlns:w="${W}"`])
	})

	it("handles single-quoted attribute values", () => {
		const decls = rootNamespaceDecls(`<w:document xmlns:w='${W}' custom='a > b'/>`)
		expect(decls).toEqual([`xmlns:w="${W}"`])
	})

	it("does not end the root tag at a > inside an attribute value", () => {
		const decls = rootNamespaceDecls(`<w:document mc:Ignorable="w14 >" xmlns:w14="${W14}" xmlns:w="${W2(W)}"/>`)
		expect(decls).toEqual([`xmlns:w14="${W14}"`, `xmlns:w="${W2(W)}"`])
	})

	it("returns [] without a root start tag", () => {
		expect(rootNamespaceDecls("<?xml broken")).toEqual([])
	})
})

describe("fragmentNamespaces", () => {
	it("keeps the root's declarations and adds missing required prefixes", () => {
		const part = `<w:document xmlns:w="${W}" xmlns:w14="${W14}" custom="1"/>`
		const decls = fragmentNamespaces(part, [
			{ prefix: "w", uri: W },
			{ prefix: "a", uri: "http://schemas.openxmlformats.org/drawingml/2006/main" },
		])
		expect(decls).toContain(`xmlns:w="${W}"`)
		expect(decls).toContain(`xmlns:w14="${W14}"`)
		expect(decls).toContain('xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"')
	})

	it("does not override a required prefix the root declares differently", () => {
		const decls = fragmentNamespaces(`<x:worksheet xmlns="http://odd.example/ns" xmlns:r="urn:rel"/>`, [
			{ prefix: "", uri: "http://main.example/ns" },
			{ prefix: "r", uri: "http://other.example/rel" },
		])
		expect(decls).toBe('xmlns="http://odd.example/ns" xmlns:r="urn:rel"')
	})
})

describe("fragment round-trip", () => {
	it("parses and serializes a fragment back to identical bytes", () => {
		const WPS = "http://schemas.microsoft.com/office/word/2010/wordprocessingShape"
		const part = `<w:document xmlns:w="${W}" xmlns:w14="${W14}" xmlns:wps="${WPS}"/>`
		const nsDecls = fragmentNamespaces(part, [])
		const fragment = `<w:p w14:paraId="1A2B3C4D" w14:textId="11223344"><w:r><w:t>lo & be</w:t></w:r></w:p>`
		const doc = parseFragment(fragment, "w:body", nsDecls)
		expect(serializeFragmentChildren(doc, nsDecls)).toBe(
			`<w:p w14:paraId="1A2B3C4D" w14:textId="11223344"><w:r><w:t>lo &amp; be</w:t></w:r></w:p>`,
		)
	})

	it("parses a fragment whose attributes use prefixes declared only on the root", () => {
		const part = `<w:document xmlns:w="${W}" xmlns:w14="${W14}"/>`
		const nsDecls = fragmentNamespaces(part, [])
		const doc = parseFragment(`<w:p w14:paraId="01"/>`, "w:body", nsDecls)
		expect(doc.documentElement?.childNodes.item(0)).toBeTruthy()
	})

	it("rejects a fragment with an unbound prefix as corrupt", () => {
		expect(() => parseFragment(`<w:p zz:x="1"/>`, "w:body", `xmlns:w="${W}"`)).toThrow(
			/corrupt|\[corrupt\]|XML parse failed/,
		)
	})
})

describe("parseXml", () => {
	it("throws a typed DocumentError with code corrupt on malformed XML", () => {
		try {
			parseXml(`<a><b></a>`)
			expect.unreachable()
		} catch (err) {
			const e = err as { code?: string; message?: string }
			expect(e.code).toBe("corrupt")
			expect(e.message).toMatch(/^XML parse failed: /)
		}
	})
})

function W2(uri: string): string {
	return uri
}
